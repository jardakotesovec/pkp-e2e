#!/usr/bin/env node
// seed-facts.js — the generated part of docs/process/seed-facts.md, read from
// apps/<app>/playwright/support/app.context.js (which requires the app's
// fixtures/bootstrap.js). Both modules export plain data, so this script
// requires them and renders; nothing is parsed from source text.
//
// run: npm run seed-facts             print the block
//      npm run seed-facts -- --write  replace the block in seed-facts.md
//      npm run seed-facts -- --check  exit 1 when the file's block is stale
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const APPS = ['ojs', 'omp', 'ops'];
const DOC = path.join(root, 'docs/process/seed-facts.md');
const START = '<!-- generated:start -->';
const END = '<!-- generated:end -->';

// Permission level of a scenario role key: the roleId of the default user
// group `default.groups.name.<key>` in each app's registry/userGroups.xml
// (the constants are listed in users.md section 1). Read from the three
// checkouts on 2026-09-03; the sets differ per app but no key maps to two
// levels. Add a key here when a fixture uses one that is missing.
const LEVEL = {
    manager: 'MANAGER',
    editor: 'MANAGER',
    productionEditor: 'MANAGER',
    sectionEditor: 'SUB_EDITOR',
    guestEditor: 'SUB_EDITOR',
    copyeditor: 'ASSISTANT',
    designer: 'ASSISTANT',
    funding: 'ASSISTANT',
    indexer: 'ASSISTANT',
    layoutEditor: 'ASSISTANT',
    marketing: 'ASSISTANT',
    proofreader: 'ASSISTANT',
    editorialBoardMember: 'ASSISTANT',
    author: 'AUTHOR',
    translator: 'AUTHOR',
    volumeEditor: 'AUTHOR',
    chapterAuthor: 'AUTHOR',
    externalReviewer: 'REVIEWER',
    internalReviewer: 'REVIEWER',
    reader: 'READER',
    subscriptionManager: 'SUBSCRIPTION_MANAGER',
};

const levelOf = (key) => {
    if (!LEVEL[key]) throw new Error(`seed-facts: no permission level known for role key "${key}"; add it to LEVEL in bin/seed-facts.js`);
    return `ROLE_ID_${LEVEL[key]}`;
};

// {en: 'X', fr_CA: 'Y'} → `"X" (fr_CA "Y")`; a bare string is passed through.
const loc = (v) => {
    if (v == null) return '—';
    if (typeof v !== 'object') return `"${v}"`;
    const {en, ...rest} = v;
    const others = Object.entries(rest).map(([l, s]) => `${l} "${s}"`);
    return `"${en}"` + (others.length ? ` (${others.join(', ')})` : '');
};

// Any field of a section/series beyond its id and title, printed as-is so a
// new fixture field shows up here without a code change.
const extras = (obj, skip) =>
    Object.entries(obj)
        .filter(([k]) => !skip.includes(k))
        .map(([k, v]) => `${k}: ${typeof v === 'object' ? loc(v) : JSON.stringify(v)}`);

const renderSections = (app) => {
    if (app.series) {
        return app.series.map((s) => `\`${s.path}\` ${loc(s.title)}` + extraText(extras(s, ['path', 'title'])));
    }
    return (app.sections || []).map((s) => `\`${s.abbrev}\` ${loc(s.title)}` + extraText(extras(s, ['abbrev', 'title'])));
};
const extraText = (list) => (list.length ? ` — ${list.join('; ')}` : '');

const flattenCategories = (cats, prefix = []) =>
    cats.flatMap((c) => {
        const chain = [...prefix, c.path];
        return [`\`${chain.join('/')}\` ${loc(c.title)}`, ...flattenCategories(c.children || [], chain)];
    });

const renderIssues = (issues) =>
    (issues || []).map((i) => `Vol ${i.volume} No ${i.number} (${i.year}) — ${i.published ? 'published' : 'unpublished'}`);

const bullets = (items, none) => (items.length ? items.map((x) => `  - ${x}`).join('\n') : `  - ${none}`);

function load(app) {
    const ctx = require(path.join(root, 'apps', app, 'playwright/support/app.context.js'));
    return {app, ctx, seed: ctx.seed.bootstrap};
}

function userCell(u) {
    if (!u) return '—';
    const assign = u.sections || u.series;
    const roles = u.roles.join(', ') + (assign ? ` (${assign.join(', ')})` : '');
    const levels = [...new Set(u.roles.map(levelOf))].join(', ');
    return `${roles} · ${levels}`;
}

function generate() {
    const apps = APPS.map(load);
    const out = [];
    out.push(`Generated by \`bin/seed-facts.js\` from \`apps/<app>/playwright/fixtures/bootstrap.js\` and \`support/app.context.js\`. Do not edit by hand; run \`npm run seed-facts -- --write\`.`);
    out.push('');
    for (const {app, ctx, seed} of apps) {
        const c = seed.context;
        out.push(`### ${app.toUpperCase()}`);
        out.push('');
        out.push(`- Context: \`${c.path}\` — ${loc(c.name)}, acronym ${loc(c.acronym)}`);
        out.push(`- Locales: primary \`${c.primaryLocale}\`; supported ${c.supportedLocales.map((l) => `\`${l}\``).join(', ')}`);
        out.push(`- ${seed.series ? 'Series' : 'Sections'}:`);
        out.push(bullets(renderSections(seed), 'none'));
        out.push('- Categories (parent/child by path):');
        out.push(bullets(flattenCategories(seed.categories || []), 'none'));
        out.push('- Issues:');
        out.push(bullets(renderIssues(seed.issues), ctx.capabilities.hasIssues ? 'none' : 'none (the app has no issues)'));
        out.push('');
    }

    out.push('### Users');
    out.push('');
    out.push('Roles are scenario role keys (sub-editor assignments in brackets); the level is the PHP role constant of the default user group that key resolves to (users.md section 1). `—` means the app does not enrol that user. `admin`, the installer\'s site administrator (`ROLE_ID_SITE_ADMIN`), is not part of the seed and is enrolled in every context the test API creates.');
    out.push('');
    const names = [];
    for (const {seed} of apps) for (const u of seed.users) if (!names.includes(u.username)) names.push(u.username);
    out.push(`| Username | ${apps.map(({app}) => app.toUpperCase()).join(' | ')} |`);
    out.push(`|---|${apps.map(() => '---').join('|')}|`);
    for (const name of names) {
        const cells = apps.map(({seed}) => userCell(seed.users.find((u) => u.username === name)));
        out.push(`| \`${name}\` | ${cells.join(' | ')} |`);
    }
    out.push('');

    out.push('### Actor map (`seed.actors`)');
    out.push('');
    out.push('The archetype a shared test asks for and the seeded username it resolves to; `null` where the app has no such role.');
    out.push('');
    const archetypes = [];
    for (const {ctx} of apps) for (const a of Object.keys(ctx.seed.actors)) if (!archetypes.includes(a)) archetypes.push(a);
    out.push(`| Archetype | ${apps.map(({app}) => app.toUpperCase()).join(' | ')} |`);
    out.push(`|---|${apps.map(() => '---').join('|')}|`);
    for (const a of archetypes) {
        const cells = apps.map(({ctx}) => (ctx.seed.actors[a] ? `\`${ctx.seed.actors[a]}\`` : 'null'));
        out.push(`| ${a} | ${cells.join(' | ')} |`);
    }
    return out.join('\n');
}

function readDoc() {
    const text = fs.readFileSync(DOC, 'utf8');
    const s = text.indexOf(START);
    const e = text.indexOf(END);
    if (s < 0 || e < 0 || e < s) throw new Error(`seed-facts: ${path.relative(root, DOC)} lacks the ${START} … ${END} markers`);
    return {text, s: s + START.length, e};
}

function main() {
    const mode = process.argv[2] || '';
    const block = generate();
    if (mode === '') {
        process.stdout.write(block + '\n');
        return 0;
    }
    if (mode === '--write') {
        const {text, s, e} = readDoc();
        fs.writeFileSync(DOC, text.slice(0, s) + '\n' + block + '\n' + text.slice(e));
        console.log(`seed-facts: wrote the generated block to ${path.relative(root, DOC)}`);
        return 0;
    }
    if (mode === '--check') {
        const {text, s, e} = readDoc();
        const current = text.slice(s, e).trim();
        if (current === block.trim()) {
            console.log('seed-facts: the generated block is up to date');
            return 0;
        }
        const have = current.split('\n');
        const want = block.trim().split('\n');
        console.error(`seed-facts: ${path.relative(root, DOC)} is stale; run \`npm run seed-facts -- --write\`. Difference:`);
        for (const l of have) if (!want.includes(l)) console.error(`- ${l}`);
        for (const l of want) if (!have.includes(l)) console.error(`+ ${l}`);
        return 1;
    }
    console.error('usage: node bin/seed-facts.js [--write | --check]');
    return 2;
}

process.exitCode = main();
